@Suite("System theme API (v0.99.1)", .serialized)
struct SystemThemeAPITests {
    @Test func listedReservedExportAndTerminalColors() throws {
        defer { setTerminalColors(TerminalColors()) }
        #expect(getAvailableThemes().first == "system")
        let export = getThemeExportColors("system")
        #expect(export.pageBg == nil && export.cardBg == nil && export.infoBg == nil)
        let foreground = colorToRgb(try parseColor("#f8f8f2"))
        let background = colorToRgb(try parseColor("#282a36"))
        let palette = try ["#21222c", "#ff5555", "#50fa7b", "#f1fa8c", "#bd93f9", "#ff79c6", "#8be9fd", "#f8f8f2",
                           "#6272a4", "#ff6e6e", "#69ff94", "#ffffa5", "#d6acff", "#ff92df", "#a4ffff", "#ffffff"].map { colorToRgb(try parseColor($0)) }
        setTerminalColors(.init(foreground: foreground, background: background, palette: palette))
        let theme = try #require(getThemeByName("system"))
        #expect(theme.appearance == .dark)
        #expect(theme.getFgAnsi(.text) == "\u{001B}[39m")
        #expect(theme.getFgAnsi(.error).hasPrefix("\u{001B}[38;"))
    }
    @Test func faintTokens() throws {
        setTerminalColors(TerminalColors())
        let theme = try #require(getThemeByName("system"))
        #expect(theme.fg(.muted, "x") == "\u{001B}[39m\u{001B}[2mx\u{001B}[22;39m")
        #expect(theme.style("x", options: .init(fg: .token(.muted))) == "\u{001B}[39m\u{001B}[2mx\u{001B}[22m\u{001B}[39m")
    }
}

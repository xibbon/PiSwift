    private func rgb(_ hex: String) throws -> RgbColorValue { colorToRgb(try parseColor(hex)) }
    private func dracula() throws -> SystemThemeInput {
        try .init(foreground: rgb("#f8f8f2"), background: rgb("#282a36"), palette:
            ["#21222c", "#ff5555", "#50fa7b", "#f1fa8c", "#bd93f9", "#ff79c6", "#8be9fd", "#f8f8f2",
             "#6272a4", "#ff6e6e", "#69ff94", "#ffffa5", "#d6acff", "#ff92df", "#a4ffff", "#ffffff"].map(rgb))
    }
    private func terminals() throws -> [(String, SystemThemeInput)] {
        try [("dracula", dracula()), ("solarizedLight", .init(foreground: rgb("#657b83"), background: rgb("#fdf6e3"))),
             ("backgroundOnly", .init(background: rgb("#1e1e1e"))), ("midGray", .init(foreground: rgb("#ffffff"), background: rgb("#808080")))]
    }
    private let panels = ["userMessageBg", "toolPendingBg", "toolSuccessBg", "toolErrorBg", "selectedBg"]
    private func resolved(_ input: SystemThemeInput, _ token: String) throws -> RgbColorValue {
        switch generateSystemThemeColors(input).colors[token]! {
        case .string(""): return panels.contains(token) ? input.background! : input.foreground!
        case .string(let hex): return try rgb(hex)
        case .number(let index): return colorToRgb(try parseColor(index))
        }
    }
    @Test func bodyTextContrast() throws {
        for (_, input) in try terminals() {
            let text = try resolved(input, "text")
            for surface in [input.background!, try resolved(input, "selectedBg")] { #expect(wcagContrast(text, surface) >= 4.5) }
            #expect(try wcagContrast(resolved(input, "toolTitle"), resolved(input, "toolErrorBg")) >= 4.5)
        }
    }
    @Test func roleOrderAndPanels() throws {
        for (name, input) in try terminals() {
            let background = colorToOklch(.rgb(input.background!)).l
            func offset(_ token: String) throws -> Double { try colorToOklch(.rgb(resolved(input, token))).l - background }
            if name != "midGray" {
                #expect(try abs(offset("text")) > abs(offset("muted")))
                #expect(try abs(offset("muted")) > abs(offset("dim")))
            }
            let lighter = generateSystemThemeColors(input).appearance == .dark
            for panel in panels {
                #expect(try wcagContrast(resolved(input, panel), input.background!) < 2)
                #expect(try (offset(panel) > 0) == lighter)
            }
        }
    }
    @Test func foregroundAndPalette() throws {
        let input = try dracula()
        #expect(generateSystemThemeColors(input).colors["text"] == .string(""))
        #expect(generateSystemThemeColors(try terminals()[1].1).colors["text"] != .string(""))
        #expect(try abs(colorToOklch(.rgb(resolved(input, "error"))).h - colorToOklch(.rgb(input.palette![1])).h) < 8)
    }
    @Test func grayscale() throws {
        var input = try dracula(); input.saturation = 0
        #expect(try colorToOklch(.rgb(resolved(input, "error"))).c < 0.005)
    }
